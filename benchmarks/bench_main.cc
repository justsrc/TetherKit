// Performance benchmark entry point.
//
// The output is a complete Markdown document (stdout) that can be redirected directly into
// docs/BENCHMARKS.md:
//
//   ./build-rel/bin/tetherkit_bench > docs/BENCHMARKS.md
//
// Progress messages go to stderr and do not pollute the report.
#include <cstdio>
#include <string>
#include <vector>

#include "bench_common.h"
#include "bench_net.h"
#include "bench_rndis.h"
#include "harness.h"
#include "tetherkit/common/scheduling.h"
#include "tetherkit/version.h"

int main() {
  // The benchmark thread itself runs at data-path QoS; otherwise it may be scheduled onto an
  // efficiency core and the measured numbers would be worse than at actual runtime.
  tetherkit::ConfigureCurrentThread("bench", tetherkit::ThreadRole::kDataPath);

  const std::string version{tetherkit::GetVersionString()};
  std::printf("# TetherKit Performance Benchmarks\n\n");
  std::printf("Automatically generated by `tetherkit_bench` -- %s\n\n", version.c_str());
  std::printf("> Regenerate: `./build-rel/bin/tetherkit_bench > docs/BENCHMARKS.md`\n");
  std::printf(
      "> Must use a **Release build without sanitizers**, otherwise the numbers are not "
      "meaningful.\n\n");

  tetherkit::bench::PrintEnvironment();

  std::fprintf(stderr, "Starting measurements...\n");

  {
    tetherkit::bench::Runner runner;
    tetherkit::bench::RegisterCommonBenchmarks(runner);
    tetherkit::bench::PrintMarkdownReport(runner.RunAll(), "Infrastructure (tk_common)");
  }
  {
    tetherkit::bench::Runner runner;
    tetherkit::bench::RegisterRndisBenchmarks(runner);
    tetherkit::bench::PrintMarkdownReport(runner.RunAll(), "RNDIS encode/decode (tk_rndis)");
  }
  {
    // The link layer requires root. When skipped, leave a trace in the report -- otherwise
    // readers cannot tell whether this report "measured it and found no problem" or "never
    // measured it at all".
    tetherkit::bench::Runner runner;
    std::string skip_reason;
    if (tetherkit::bench::RegisterNetBenchmarks(runner, skip_reason)) {
      tetherkit::bench::PrintMarkdownReport(runner.RunAll(),
                                            "feth / BPF link layer (tk_net, requires root)");
      // Must be torn down here, not left to static destruction -- see bench_net.h for the reason.
      tetherkit::bench::ShutdownNetBenchmarks();
    } else {
      std::printf("## feth / BPF link layer (tk_net, requires root)\n\n");
      std::printf("**Not measured in this run** -- %s.\n\n", skip_reason.c_str());
      std::printf("To measure: `sudo ./build/bin/tetherkit_bench > docs/BENCHMARKS.md`\n\n");
      std::fprintf(stderr, "  Skipping link-layer benchmarks: %s\n", skip_reason.c_str());
    }
  }

  std::fprintf(stderr, "Measurements complete.\n");
  return 0;
}
